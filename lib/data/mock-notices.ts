export function getNotice(id: string): Notice | undefined {
  return NOTICES.find((n) => n.id === id);
}
export function getNoticesByCategory(cat: NoticeCategory): Notice[] {
  return NOTICES.filter((n) => n.category === cat);
}
export function getCategoryMeta(key: NoticeCategory) {
  return NOTICE_CATEGORIES.find((c) => c.key === key) || NOTICE_CATEGORIES[0];
}